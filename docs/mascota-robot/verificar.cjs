const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
  const b=await chromium.launch({channel:'chrome',headless:true});
  const p=await b.newPage({viewport:{width:1100,height:980}});
  const errors=[];
  p.on('pageerror',e=>errors.push(e.message));
  await p.goto('http://127.0.0.1:5182/mascota-preview.html');
  await p.waitForSelector('.mascot-robot');
  await p.locator('.states').waitFor({state:'visible'});
  await p.waitForTimeout(400);
  await p.screenshot({path:'docs/mascota-robot/preview.png'});
  const css=fs.readFileSync('web/src/components/Mascot.css','utf8');
  const svg=await p.locator('svg.mascot-robot').first().evaluate((e,css)=>{
    const copy=e.cloneNode(true);
    copy.setAttribute('xmlns','http://www.w3.org/2000/svg');
    copy.setAttribute('width','160');
    copy.setAttribute('height','160');
    const style=document.createElementNS('http://www.w3.org/2000/svg','style');
    style.textContent=css;
    copy.prepend(style);
    return new XMLSerializer().serializeToString(copy);
  },css);
  fs.writeFileSync('web/public/yachi-robot.svg',svg);
  const animations=await p.locator('.states .robot-head').evaluateAll(es=>es.map(e=>getComputedStyle(e).animationName));
  assert.deepEqual(animations,['robot-float','robot-think','robot-float','robot-happy']);
  await p.emulateMedia({reducedMotion:'reduce'});
  assert((await p.locator('.mascot-robot *').evaluateAll(es=>es.every(e=>getComputedStyle(e).animationName==='none'))));
  await p.goto('http://127.0.0.1:5182/yachi-robot.svg');
  assert.equal(await p.locator('svg').count(),1);
  assert.deepEqual(errors,[]);
  await p.goto('http://127.0.0.1:5182');
  await p.evaluate(()=>localStorage.setItem('yt-consent-2026-10c','1'));
  await p.reload();
  await p.waitForSelector('.mascot-robot');
  assert(await p.locator('.mascot-robot').count()>=2);
  assert.equal(await p.locator('.mascot-robot image').count(),0);
  if(errors.length)console.log('Avisos del chat (servicios externos): '+errors.join(', '));
  console.log('OK: cuatro estados, movimiento reducido, SVG independiente y robot integrado en el chat. SVG: '+Buffer.byteLength(svg)+' bytes.');
  await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
