// Ejecutar desde IDEATHON con PLAYWRIGHT_MODULE apuntando a la instalación disponible.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5182',{waitUntil:'domcontentloaded'});
  await page.evaluate(()=>{
    localStorage.setItem('yt-consent-2026-10c','1');
    localStorage.setItem('yt-theme','light');
    localStorage.setItem('yt-chats',JSON.stringify(['Por qué no te dijiste a todos','Solicitud de residencia','Sala de estudio'].map((title,i)=>({id:'audit-'+i,title,at:Date.now(),renamed:true,msgs:[{id:'msg-'+i,role:'user',text:title}]}))));
  });
  await page.reload({waitUntil:'domcontentloaded'});
  const toggle=page.locator('.topbar button[aria-controls="chat-sidebar"]');
  assert.equal(await page.locator('.rail').evaluate(e=>e.getBoundingClientRect().width),260);
  await toggle.click();
  assert.equal(await toggle.getAttribute('aria-expanded'),'false');
  assert.equal(await page.locator('.rail').evaluate(e=>e.getBoundingClientRect().width),64);
  assert.equal(await page.locator('.chat-list .item').count(),3);
  assert.equal(await page.locator('.chat-list .item').first().getAttribute('title'),'Por qué no te dijiste a todos');
  assert.equal(await page.locator('.rail-label').first().isVisible(),false);
  assert.equal(await page.locator('.chat-more').first().isVisible(),false);
  const footer=await page.locator('.rail .foot .item').evaluateAll(es=>es.map(e=>({name:e.getAttribute('aria-label'),x:e.getBoundingClientRect().x,y:e.getBoundingClientRect().y})));
  assert.deepEqual(footer.map(e=>e.name),['Cómo funciona','Aviso de uso de datos','Portal de administración']);
  assert(footer.every(e=>e.x>=0&&e.x<64));
  assert(footer[0].y<footer[1].y&&footer[1].y<footer[2].y);
  assert.equal(await page.locator('.send').isDisabled(),true);
  assert.equal(await page.locator('.send').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(39, 97, 142)');
  await page.locator('#ask').fill('Consulta de prueba');
  assert.equal(await page.locator('.send').isEnabled(),true);
  assert.equal(await page.locator('.send').evaluate(e=>getComputedStyle(e).color),'rgb(255, 255, 255)');
  await page.screenshot({path:path.join(__dirname,'lateral-minimizado-real.png')});
  await page.locator('.chat-list .item').nth(1).click();
  assert.equal(await page.locator('.msg-user').innerText(),'Solicitud de residencia');
  await page.locator('.rail .foot button').first().click();
  assert.equal(await page.getByRole('dialog').isVisible(),true);
  await page.keyboard.press('Escape');
  await toggle.click();
  assert.equal(await page.locator('.rail-label').first().isVisible(),true);
  assert.equal(await page.locator('.rail').evaluate(e=>e.getBoundingClientRect().width),260);
  await toggle.click();
  await page.locator('.topbar button[title]').click();
  assert.equal(await page.locator('.send').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(39, 97, 142)');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('.app').evaluate(e=>getComputedStyle(e).gridTemplateColumns.split(' ')[0]),'0px');
  await toggle.click();
  assert.equal(await page.locator('.rail-label').first().isVisible(),true);
  assert.equal(await page.locator('.rail').evaluate(e=>e.getBoundingClientRect().width),260);
  await page.locator('.rail > .item').click();
  assert.equal(await page.locator('.app').evaluate(e=>e.classList.contains('rail-open-mobile')),false);
  await page.goto('http://127.0.0.1:5182/#/embed',{waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('.rail').count(),0);
  assert.equal(await page.locator('.chat').evaluate(e=>Math.round(e.getBoundingClientRect().width)),390);
  assert.deepEqual(errors,[]);
  console.log('OK: iconos y orden; títulos accesibles; apertura de chats y ayuda; expandir; envío azul claro/oscuro; menú móvil y widget.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
